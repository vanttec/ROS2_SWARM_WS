#!/usr/bin/env python3
"""Generate a Gazebo world holding N Holybro X500 V2 copters wired to N SITL instances.

Each copter needs its own ArduPilotPlugin with its own FDM port, and SDF has no way to
override a value inside an <include>, so the per-vehicle plugin blocks have to be written out
in full. That is what this script does -- edit it rather than the generated world.

    ./gen_x500_world.py                       # four copters 3 m apart, worlds/x500_swarm.sdf
    ./gen_x500_world.py --count 1 --out ../worlds/x500_single.sdf

SITL puts instance -I<i> on FDM port 9002 + 10*i, which is the port each wrapper listens on.
"""
import argparse
import math
import os

ROTOR_R = 0.25 / math.sqrt(2)

# (rotor, spin) in ArduCopter QUAD X channel order:
#   1 front-right CCW, 2 rear-left CCW, 3 front-left CW, 4 rear-right CW.
# A CCW rotor gets a positive velocity multiplier and its blades point +y / -y;
# a CW rotor is the mirror of that.
ROTORS = [('rotor_0', 'ccw'), ('rotor_1', 'ccw'), ('rotor_2', 'cw'), ('rotor_3', 'cw')]

# 1045 prop: lift acts at 0.75 of the 0.127 m radius, and the area is picked so that eight
# blades at the 700 rad/s cap make 43 N -- thrust to weight 2.2 on a 2.02 kg airframe.
BLADE_CP = 0.095
BLADE_AREA = 0.0016
ROTOR_VEL_MAX = 700
# At a 1 ms physics step, 0.20 makes the light rotors oscillate even at zero speed.
ROTOR_VELOCITY_P = 0.04

WORLD_HEAD = """<?xml version="1.0" ?>
<!--
  Generated by gazebo/tools/gen_x500_world.py. Edit the generator to change the world.

  {count} Holybro X500 V2 copters, {spacing} m apart along the east axis, each bound to one
  ArduPilot SITL instance:

{table}

  Spawn spacing is set by this world. The team tutorial starts all SITL instances
  at CMAC with no additional home offsets. See docs/GAZEBO_RUNBOOK.md.
-->
<sdf version="1.9">
  <world name="x500_swarm">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system"
      name="gz::sim::systems::Physics">
    </plugin>
    <plugin filename="gz-sim-sensors-system"
      name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system"
      name="gz::sim::systems::UserCommands">
    </plugin>
    <plugin filename="gz-sim-scene-broadcaster-system"
      name="gz::sim::systems::SceneBroadcaster">
    </plugin>
    <plugin filename="gz-sim-imu-system"
      name="gz::sim::systems::Imu">
    </plugin>
    <plugin filename="gz-sim-navsat-system"
      name="gz::sim::systems::NavSat">
    </plugin>

    <scene>
      <ambient>1.0 1.0 1.0</ambient>
      <background>0.6 0.75 0.9</background>
      <sky></sky>
    </scene>

    <!-- CMAC, matching sim_vehicle.py -L CMAC. Change both together for a real site. -->
    <spherical_coordinates>
      <latitude_deg>-35.363262</latitude_deg>
      <longitude_deg>149.165237</longitude_deg>
      <elevation>584</elevation>
      <heading_deg>0</heading_deg>
      <surface_model>EARTH_WGS84</surface_model>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.8 0.8 0.8 1</specular>
      <attenuation>
        <range>1000</range>
        <constant>0.9</constant>
        <linear>0.01</linear>
        <quadratic>0.001</quadratic>
      </attenuation>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>500 500</size>
            </plane>
          </geometry>
          <surface>
            <friction>
              <ode>
                <mu>100</mu>
                <mu2>50</mu2>
              </ode>
            </friction>
          </surface>
        </collision>
        <visual name="visual">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>500 500</size>
            </plane>
          </geometry>
          <material>
            <ambient>0.35 0.4 0.3 1</ambient>
            <diffuse>0.45 0.5 0.38 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
"""


def lift_drag(rotor, spin, blade):
    """One LiftDrag block: two per rotor, one per blade, mirrored about the hub."""
    sign = 1 if blade == 0 else -1
    # A CCW rotor's blades move +y at +x; reverse the forward vector for CW rotors and for
    # the opposite blade, or the rotor makes lift in the wrong direction.
    forward_y = sign * (1 if spin == 'ccw' else -1)
    return f"""      <plugin filename="gz-sim-lift-drag-system"
          name="gz::sim::systems::LiftDrag">
        <a0>0.3</a0>
        <alpha_stall>1.4</alpha_stall>
        <cla>4.2500</cla>
        <cda>0.10</cda>
        <cma>0.0</cma>
        <cla_stall>-0.025</cla_stall>
        <cda_stall>0.0</cda_stall>
        <cma_stall>0.0</cma_stall>
        <area>{BLADE_AREA}</area>
        <air_density>1.2041</air_density>
        <cp>{sign * BLADE_CP} 0 0</cp>
        <forward>0 {forward_y} 0</forward>
        <upward>0 0 1</upward>
        <link_name>x500_v2::{rotor}</link_name>
      </plugin>
"""


def control(channel, rotor, spin):
    multiplier = ROTOR_VEL_MAX if spin == 'ccw' else -ROTOR_VEL_MAX
    return f"""        <control channel="{channel}">
          <jointName>x500_v2::{rotor}_joint</jointName>
          <useForce>1</useForce>
          <multiplier>{multiplier}</multiplier>
          <offset>0</offset>
          <servo_min>1100</servo_min>
          <servo_max>1900</servo_max>
          <type>VELOCITY</type>
          <p_gain>{ROTOR_VELOCITY_P}</p_gain>
          <i_gain>0</i_gain>
          <d_gain>0</d_gain>
          <i_max>0</i_max>
          <i_min>0</i_min>
          <cmd_max>2.5</cmd_max>
          <cmd_min>-2.5</cmd_min>
          <controlVelocitySlowdownSim>1</controlVelocitySlowdownSim>
        </control>
"""


def vehicle(index, spacing, spawn_z, first_instance):
    name = f'drone{index + 1}'
    instance = first_instance + index
    fdm_port = 9002 + 10 * instance
    out = [f"""
    <!-- {name}: SITL -I{instance}, FDM {fdm_port}/{fdm_port + 1}, MAVLink TCP {5760 + 10 * instance} -->
    <model name="{name}">
      <!-- Nose north (yaw 90 in a world whose x is east), spread along the east axis. -->
      <pose degrees="true">{index * spacing} 0 {spawn_z} 0 0 90</pose>
      <include>
        <uri>model://x500_v2</uri>
      </include>

      <plugin filename="gz-sim-joint-state-publisher-system"
        name="gz::sim::systems::JointStatePublisher">
      </plugin>
"""]
    for rotor, spin in ROTORS:
        for blade in (0, 1):
            out.append(lift_drag(rotor, spin, blade))
    for rotor, _ in ROTORS:
        out.append(f"""      <plugin filename="gz-sim-apply-joint-force-system"
        name="gz::sim::systems::ApplyJointForce">
        <joint_name>x500_v2::{rotor}_joint</joint_name>
      </plugin>
""")
    out.append(f"""
      <plugin name="ArduPilotPlugin" filename="ArduPilotPlugin">
        <fdm_addr>127.0.0.1</fdm_addr>
        <fdm_port_in>{fdm_port}</fdm_port_in>
        <connectionTimeoutMaxCount>5</connectionTimeoutMaxCount>
        <lock_step>1</lock_step>
        <no_time_sync>1</no_time_sync>
        <have_32_channels>0</have_32_channels>

        <!-- Gazebo is x-forward z-up, ArduPilot is x-forward z-down. -->
        <modelXYZToAirplaneXForwardZDown degrees="true">0 0 0 180 0 0</modelXYZToAirplaneXForwardZDown>
        <gazeboXYZToNED degrees="true">0 0 0 180 0 90</gazeboXYZToNED>

        <imuName>x500_v2::imu_link::imu_sensor</imuName>

""")
    for channel, (rotor, spin) in enumerate(ROTORS):
        out.append(control(channel, rotor, spin))
    out.append("""      </plugin>
    </model>
""")
    return ''.join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--count', type=int, default=4, help='number of copters (default 4)')
    ap.add_argument('--spacing', type=float, default=3.0,
                    help='eastward spawn spacing in metres (default 3)')
    # Legs reach 0.227 m below base_link, down to the skids of the frame mesh.
    ap.add_argument('--spawn-z', type=float, default=0.24,
                    help='height of base_link with the legs on the ground (default 0.24)')
    ap.add_argument('--first-instance', type=int, default=0,
                    help='SITL instance number of the first copter (default 0). Raise it to run '
                         'a second simulation alongside one already holding 9002 and 5760.')
    ap.add_argument('--out', default=os.path.join(here, os.pardir, 'worlds', 'x500_swarm.sdf'))
    args = ap.parse_args()

    table = '\n'.join(
        f'    drone{i + 1}  -I{i}  FDM {9002 + 10 * i}/{9003 + 10 * i}  '
        f'MAVLink TCP {5760 + 10 * i}  at x = {i * args.spacing:g} m east'
        for i in range(args.count))

    body = [WORLD_HEAD.format(count=args.count, spacing=f'{args.spacing:g}',
                              table=table)]
    body += [vehicle(i, args.spacing, args.spawn_z, args.first_instance)
             for i in range(args.count)]
    body.append("""  </world>
</sdf>
""")

    out = os.path.abspath(args.out)
    with open(out, 'w') as fh:
        fh.write(''.join(body))
    print(f'wrote {out}: {args.count} copter(s), {args.spacing:g} m apart')


if __name__ == '__main__':
    main()
